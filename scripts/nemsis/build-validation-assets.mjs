#!/usr/bin/env node
/**
 * Compiles every configured NEMSIS Schematron file (national, state and
 * compliance pre-testing) into SaxonJS SEF, plus the 3.5.1 XSD set, and writes
 * them as gzip+base64 string modules the in-app validation service bundles:
 *   supabase/functions/_shared/nemsis/validation/assets.generated.ts
 *
 * Run after adding or updating any file listed in SCHEMATRON_SETS:
 *   node scripts/nemsis/build-validation-assets.mjs
 *
 * Pipeline per .sch (ISO skeleton, XSLT2, allow-foreign for NEMSIS lookup
 * variables): include -> abstract-expand -> svrl stylesheet -> SEF export.
 */
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, writeFileSync, copyFileSync } from "node:fs";
import { gzipSync } from "node:zlib";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const SCH = join(ROOT, "tests/nemsis/schematron");
const SKEL = join(SCH, "iso-skeleton");
const XSD = join(ROOT, "tests/nemsis/xsd");
const XSLT3 = join(ROOT, "node_modules/xslt3/xslt3.js");
const OUT = join(ROOT, "supabase/functions/_shared/nemsis/validation/assets.generated.ts");
const CACHE = join(ROOT, "node_modules/.cache/nemsis-validation");

/** Every Schematron file applied in-app. Add state files here. */
export const SCHEMATRON_SETS = [
  { id: "national-dem", dataset: "DEM", source: "National", file: "national/DEMDataSet.sch", include: true },
  { id: "compliance-dem", dataset: "DEM", source: "NEMSIS 2026 compliance", file: "DEMDataSet.sch", include: true },
  { id: "national-ems", dataset: "EMS", source: "National", file: "national/EMSDataSet.sch", include: true },
  { id: "compliance-ems", dataset: "EMS", source: "NEMSIS 2026 compliance", file: "EMSDataSet.sch", include: true },
  // Georgia publishes EMS rules only; its file has no external includes (the
  // include step overflows the stack on this 270 KB file, so it is skipped).
  { id: "state-ga-ems", dataset: "EMS", source: "Georgia", file: "state/GA_EMSDataSet.sch", include: false },
];

function xslt(xsl, src, out, params = []) {
  const r = spawnSync(process.execPath, ["--stack-size=8000", XSLT3, `-xsl:${xsl}`, `-s:${src}`, `-o:${out}`, ...params], { encoding: "utf8", maxBuffer: 1 << 28 });
  if (r.status !== 0) throw new Error(`XSLT failed (${xsl}): ${r.stderr || r.stdout}`);
}

const b64gz = (s) => gzipSync(Buffer.from(s, "utf8"), { level: 9 }).toString("base64");

mkdirSync(CACHE, { recursive: true });
const entries = [];
for (const set of SCHEMATRON_SETS) {
  const src = join(SCH, set.file);
  const s1 = join(CACHE, `${set.id}.1.sch`), s2 = join(CACHE, `${set.id}.2.sch`);
  const xsl = join(CACHE, `${set.id}.xsl`), sef = join(CACHE, `${set.id}.sef.json`);
  if (set.include) xslt(join(SKEL, "iso_dsdl_include.xsl"), src, s1); else copyFileSync(src, s1);
  xslt(join(SKEL, "iso_abstract_expand.xsl"), s1, s2);
  xslt(join(SKEL, "iso_svrl_for_xslt2.xsl"), s2, xsl, ["allow-foreign=true"]);
  const r = spawnSync(process.execPath, ["--stack-size=8000", XSLT3, `-xsl:${xsl}`, `-export:${sef}`, "-nogo", "-relocate:on"], { encoding: "utf8" });
  if (r.status !== 0) throw new Error(`SEF export failed (${set.id}): ${r.stderr || r.stdout}`);
  const version = /schemaVersion="([^"]*)"/.exec(readFileSync(src, "utf8"))?.[1] ?? null;
  entries.push({ id: set.id, dataset: set.dataset, source: set.source, file: set.file, version, sef: b64gz(readFileSync(sef, "utf8")) });
  console.log(`compiled ${set.id} (${version})`);
}

const xsd = Object.fromEntries(readdirSync(XSD).filter((f) => f.endsWith(".xsd")).sort().map((f) => [f, readFileSync(join(XSD, f), "utf8")]));

const body = `// GENERATED by scripts/nemsis/build-validation-assets.mjs — do not edit.
export interface SchematronAsset { id: string; dataset: "DEM" | "EMS"; source: string; file: string; version: string | null; sef: string }
export const SCHEMATRON_ASSETS: SchematronAsset[] = ${JSON.stringify(entries)};
/** gzip+base64 JSON map of XSD file name -> contents (NEMSIS 3.5.1). */
export const XSD_BUNDLE: string = ${JSON.stringify(b64gz(JSON.stringify(xsd)))};
`;
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, body);

// libxml2 (xmllint-wasm) vendored for in-thread use: the package wrapper needs
// worker_threads, which the edge runtime does not implement.
const XW = join(ROOT, "node_modules/xmllint-wasm");
const glue = readFileSync(join(XW, "xmllint-browser.mjs"), "utf8");
const core = glue.slice(0, glue.indexOf("if (typeof exports === 'object' && typeof module === 'object')"));
writeFileSync(join(dirname(OUT), "xmllint-vendor.generated.ts"), `// GENERATED from xmllint-wasm@${JSON.parse(readFileSync(join(XW, "package.json"), "utf8")).version} (MIT; libxml2 compiled to WebAssembly)
// by scripts/nemsis/build-validation-assets.mjs — do not edit.
// deno-lint-ignore-file
// @ts-nocheck
${core}
export const XMLLINT_WASM_GZ_B64 = ${JSON.stringify(gzipSync(readFileSync(join(XW, "xmllint.wasm")), { level: 9 }).toString("base64"))};
export const XmllintModule = Module;
`);
console.log("wrote xmllint-vendor.generated.ts");
console.log(`wrote ${OUT} (${(body.length / 1024).toFixed(0)} KB)`);
